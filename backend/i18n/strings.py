def t(lang: str, key: str, **kwargs: Any) -> str:
    lang = lang if lang in SUPPORTED_LANGS else DEFAULT_LANG
    table = _STRINGS.get(lang, _STRINGS[DEFAULT_LANG])
    template = table.get(key) or _STRINGS[DEFAULT_LANG].get(key) or key
    try:
        return template.format(**kwargs) if kwargs else template
    except KeyError:
        return template


def ui_strings(lang: str) -> dict[str, str]:
    lang = lang if lang in SUPPORTED_LANGS else DEFAULT_LANG
    src = _STRINGS.get(lang, _STRINGS[DEFAULT_LANG])
    return {k.split(".", 1)[1]: v for k, v in src.items() if k.startswith("ui.")}
